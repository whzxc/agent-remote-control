export async function generateTopology(inputs) {
  const [{ compactLayout, compactRoots }, { TopologyAnimator }, { TopologyPainter }, { PortraitPainter }, { DEFAULTS }] = await Promise.all([
    import('../ui/topology/compact.ts'), import('../ui/topology/animate.ts'),
    import('../ui/topology/render.ts'), import('../ui/topology/portraitRender.ts'), import('../ui/topology/solve.ts'),
  ]);
  const window = new Window();
  const previous = globalThis.document;
  globalThis.document = window.document;
  try {
    const scenes = {};
    for (const input of inputs) {
      const { scene, expanded } = input.solver;
      const params = DEFAULTS;
      const plan = compactRoots(scene.left, scene.right, scene, input.orientation, params);
      const layout = compactLayout(scene, plan, new Set(expanded), params, input.orientation);
      const animator = new TopologyAnimator(params);
      animator.setTargets(layout);
      animator.appearance(input.paintNodes);
      animator.step(0, true);
      const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
      const painter = layout.portrait ? new PortraitPainter(svg, 'design') : new TopologyPainter(svg, 'design');
      painter.paint(animator, input.paintNodes);
      const paths = [...svg.querySelectorAll('path')].filter(path => path.getAttribute('d') && !path.classList.contains('topology-path-hit') && !path.closest('defs')).map(path => {
        const left = path.closest('.left') || path.classList.contains('left');
        const role = left ? 'var(--role-source)' : 'var(--role-agent)';
        const wire = path.hasAttribute('fill') && path.getAttribute('fill').startsWith('url(');
        const ear = path.classList.contains('topology-ear');
        return { d: path.getAttribute('d'), fill: wire ? role : 'none', stroke: wire ? 'none' : role,
          strokeWidth: wire ? '1px' : `${path.getAttribute('stroke-width') ?? 3}px`, opacity: Number(path.getAttribute('opacity') ?? 1) };
      });
      const nodes = input.nodes.flatMap(node => {
        const geometry = layout.wings.flatMap(wing => wing.nodes).find(item => item.id === node.id);
        if (!geometry || geometry.opacity === 0) return [];
        return [{ ...node, x: geometry.x + input.origin.x - geometry.size * geometry.scale / 2,
          y: geometry.y + input.origin.y - geometry.size * geometry.scale / 2, scale: geometry.size * geometry.scale / 44 }];
      });
      const size = layout.hub.Re * 240 / 130;
      scenes[input.name] = { ...input.presentation, origin: input.origin, paths, nodes,
        hub: { x: layout.hub.x + input.origin.x - size / 2, y: layout.hub.y + input.origin.y - size / 2, width: size, height: size } };
      painter.dispose();
    }
    return `import type { TopologySceneData } from '../modules/homepage-scene';\n\n// Generated by npm run design:topology. Do not edit.\nexport const topologyScenes = ${JSON.stringify(scenes, null, 2)} satisfies Record<string, TopologySceneData>;\n`;
  } finally { globalThis.document = previous; await window.happyDOM.close(); }
}

async function captureInputs() {
  const [{ default: config }, { chromium }] = await Promise.all([import('../adg.config.mjs'), import('playwright')]);
  const stop = await config.compare.start({ port: 5293, root });
  const browser = await chromium.launch();
  const inputs = [];
  try {
    for (const [name, fixture, width, height] of cases) {
      const spec = config.compare.fixture(fixture);
      const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce', timezoneId: spec.timezone });
      await page.addInitScript(clock => {
        const OriginalDate = Date, fixed = OriginalDate.parse(clock);
        Date = class extends OriginalDate { constructor(...args) { super(...(args.length ? args : [fixed])); } static now() { return fixed; } };
      }, spec.clock);
      await page.goto(`http://localhost:5293${spec.url}`);
      await config.compare.ready(page, fixture);
      await page.evaluate(() => document.fonts.ready);
      const input = await page.evaluate(({ name, width, height }) => {
        const model = window.__ARC_VIEW_MODEL__().topology;
        const strip = node => node;
        const solver = { ...model.solver, scene: { ...model.solver.scene, left: model.solver.scene.left.map(strip), right: model.solver.scene.right.map(strip) } };
        const nodes = model.nodes.flatMap(node => {
          const element = [...document.querySelectorAll('.topology-node')].find(element => element.dataset.nodeId === node.id);
          if (!element || getComputedStyle(element).opacity === '0') return [];
          const label = element.querySelector('.graph-node-name,.topology-group-label');
          const bounds = element.getBoundingClientRect(), labelBounds = label?.getBoundingClientRect();
          let brand = node.platform === 'claude' ? 'claude-code' : node.platform === 'dsh' ? 'deepseek' : node.platform;
          if (brand === 'anthropic' && label?.textContent.startsWith('Claude')) brand = 'claude';
          const device = node.id.startsWith('device:');
          return [{ id: node.id, label: label?.textContent.replace(/LAN/, '\nLAN') ?? '', brand: device ? 'codex' : brand,
            ...(device ? { device: true } : {}), wing: node.side === -1 ? 'left' : 'right',
            capsule: !!element.querySelector('.node-capsule'), width: parseFloat(element.querySelector('.node-capsule')?.style.width ?? '48'),
            ...(node.group ? { group: { count: node.group.members.length, layout: model.orientation === 'portrait' ? 'agent' : 'vertical' } } : {}),
            ...(labelBounds?.width ? { labelBox: { x: labelBounds.x - bounds.x, y: labelBounds.y - bounds.y, width: labelBounds.width, height: labelBounds.height } } : {}),
            items: [...element.querySelectorAll('.node-capsule-disc')].map(item => ({ kind: item.dataset.kind, phase: item.dataset.phase })),
            readings: (node.quota?.windows ?? []).filter(window => window.id === 'weekly').map(window => ({ value: 100 - window.usedPercent, color: window.usedPercent >= 50 ? 'var(--warning)' : 'var(--success)', elapsed: 4 / 7 })),
          }];
        });
        const chinese = document.documentElement.lang.startsWith('zh');
        return { name, orientation: model.orientation, solver, nodes,
          paintNodes: model.nodes.map(({ id, side, parent, state, attention, selected, label, hasChildren }) => ({ id, side, parent, state, attention, selected, label, hasChildren })),
          origin: model.origin, presentation: { width, height, fixture: name, nav: true, time: '08:00', date: chinese ? '1月1日 · 周四' : 'January 1 · Thu', ...(chinese ? { language: 'zh-CN' } : {}) } };
      }, { name, width, height });
      const scenario = spec.url.match(/scenario=([^&]+)/)[1];
      input.fixture = { name: decodeURIComponent(scenario), data: JSON.parse(await readFile(`${root}/tooling/acceptance/scenarios/${decodeURIComponent(scenario)}.json`, 'utf8')) };
      inputs.push(input);
      await page.close();
    }
    return inputs;
  } finally { await browser.close(); await stop(); }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const inputs = await captureInputs();
  await writeFile(`${root}/design/fixtures/topology-input.json`, `${JSON.stringify(inputs, null, 2)}\n`);
  await writeFile(`${root}/design/fixtures/topology.ts`, await generateTopology(inputs));
  console.log(`Generated ${inputs.length} topology scenes from browser fixtures and production solvers.`);
}
